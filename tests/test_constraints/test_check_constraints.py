"""
Tests for CHECK constraints that compare an enum column, when the enum values change (issue #134).
"""

import pytest
import sqlalchemy
from alembic.operations import Operations
from alembic.runtime.migration import MigrationContext
from sqlalchemy import CheckConstraint, Column, DateTime, Integer, MetaData, Table
from sqlalchemy.dialects import postgresql
from sqlalchemy.engine import Connection
from sqlalchemy.exc import IntegrityError

from tests.base.render_and_run import compare_and_run
from tests.schemas import ANOTHER_SCHEMA_NAME, DEFAULT_SCHEMA, USER_TABLE_NAME

CONSTRAINT_NAME = "ck_user_deleted_at"


def _create_table(connection: "Connection", schema: str = DEFAULT_SCHEMA):
    database_schema = MetaData(schema=schema)
    enum_type = postgresql.ENUM("active", "deleted", name="userstatus", schema=schema)
    Table(
        USER_TABLE_NAME,
        database_schema,
        Column("id", Integer, primary_key=True),
        Column("status", enum_type, nullable=False),
        Column("deleted_at", DateTime, nullable=True),
        CheckConstraint(
            f"(status = 'deleted'::{schema}.userstatus) = (deleted_at IS NOT NULL)",
            name=CONSTRAINT_NAME,
        ),
    )
    database_schema.create_all(connection)
    connection.execute(
        sqlalchemy.text(
            f"INSERT INTO {schema}.{USER_TABLE_NAME} (status, deleted_at) VALUES ('active', NULL), ('deleted', now())"
        )
    )


def _constraint_definition(connection: "Connection", schema: str = DEFAULT_SCHEMA):
    return connection.execute(
        sqlalchemy.text(
            """
            SELECT pg_get_constraintdef(c.oid)
            FROM pg_constraint c
            JOIN pg_namespace n ON n.oid = c.connamespace
            WHERE c.conname = :name AND n.nspname = :schema
            """
        ),
        {"name": CONSTRAINT_NAME, "schema": schema},
    ).scalar()


def _sync(connection: "Connection", new_values, schema: str = DEFAULT_SCHEMA, renamed=()):
    Operations(MigrationContext.configure(connection)).sync_enum_values(
        schema,
        "userstatus",
        new_values,
        [(USER_TABLE_NAME, "status")],
        enum_values_to_rename=list(renamed),
    )


def test_check_constraint_survives_adding_a_value(connection: "Connection"):
    _create_table(connection)

    _sync(connection, ["active", "deleted", "pending"])

    assert _constraint_definition(connection) is not None, "the CHECK constraint must not be dropped"
    with pytest.raises(IntegrityError):
        with connection.begin_nested():
            connection.execute(
                sqlalchemy.text(f"INSERT INTO {USER_TABLE_NAME} (status, deleted_at) VALUES ('deleted', NULL)")
            )
    connection.execute(sqlalchemy.text(f"INSERT INTO {USER_TABLE_NAME} (status) VALUES ('pending')"))


def test_check_constraint_follows_a_renamed_value(connection: "Connection"):
    _create_table(connection)

    _sync(connection, ["active", "removed"], renamed=[("deleted", "removed")])

    definition = _constraint_definition(connection)
    assert "'removed'::" in definition and "'deleted'" not in definition
    with pytest.raises(IntegrityError):
        with connection.begin_nested():
            connection.execute(
                sqlalchemy.text(f"INSERT INTO {USER_TABLE_NAME} (status, deleted_at) VALUES ('removed', NULL)")
            )


def test_check_constraint_in_another_schema(connection: "Connection"):
    _create_table(connection, ANOTHER_SCHEMA_NAME)

    _sync(connection, ["active", "deleted", "pending"], schema=ANOTHER_SCHEMA_NAME)

    assert _constraint_definition(connection, ANOTHER_SCHEMA_NAME) is not None


def test_autogenerate_passes_the_check_constraints_to_the_migration(connection: "Connection"):
    """Found at generation time, as partial indexes are: the migration then runs in offline mode too."""
    _create_table(connection)
    target = MetaData()
    Table(
        USER_TABLE_NAME,
        target,
        Column("id", Integer, primary_key=True),
        Column("status", postgresql.ENUM("active", "deleted", "pending", name="userstatus"), nullable=False),
        Column("deleted_at", DateTime, nullable=True),
        CheckConstraint("(status = 'deleted'::userstatus) = (deleted_at IS NOT NULL)", name=CONSTRAINT_NAME),
    )
    definition = "CHECK (((status = 'deleted'::userstatus) = (deleted_at IS NOT NULL)))"

    def migration(values):
        return f"""
        # ### commands auto generated by Alembic - please adjust! ###
        op.sync_enum_values(
            enum_schema='public',
            enum_name='userstatus',
            new_values={values!r},
            affected_columns=[TableReference(table_schema='public', table_name='{USER_TABLE_NAME}', column_name='status')],
            enum_values_to_rename=[],
            check_constraints_to_recreate=[
                TableCheckConstraint(
                    table='public.{USER_TABLE_NAME}',
                    name='{CONSTRAINT_NAME}',
                    definition={definition!r},
                ),
            ],
        )
        # ### end Alembic commands ###
        """

    compare_and_run(
        connection,
        target,
        expected_upgrade=migration(["active", "deleted", "pending"]),
        expected_downgrade=migration(["active", "deleted"]),
        expected_imports=None,
    )
    assert _constraint_definition(connection) == definition


def test_deleting_a_value_the_check_constraint_refers_to_fails(connection: "Connection"):
    _create_table(connection)
    connection.execute(sqlalchemy.text(f"DELETE FROM {USER_TABLE_NAME} WHERE status = 'deleted'"))

    with pytest.raises(sqlalchemy.exc.DataError, match="invalid input value for enum"):
        _sync(connection, ["active", "pending"])
